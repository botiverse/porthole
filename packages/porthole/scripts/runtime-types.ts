/**
 * Embeds the capability runtime's type definitions (P085: `types/runtime/v<n>/*.d.ts`, each
 * capability's API, versioned with its contract) into `src/runtime/types.generated.ts`, the
 * module the manual teaches them from. A module rather than files beside it, so every entry point
 * still bundles whole (P075); the files ship in the package for a page's own TypeScript.
 *
 *   node scripts/runtime-types.ts          # write the module
 *   node scripts/runtime-types.ts --check  # exit 1 if it isn't what the files hold
 *
 * `test/runtime.test.ts` runs the check, so the manual can't drift from the files.
 */
import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
export const GENERATED = path.join(root, "src/runtime/types.generated.ts");
const TYPES = path.join(root, "types/runtime");

/** The module's text, from the files. */
export async function generate(): Promise<string> {
  const versions = (await readdir(TYPES)).filter((name) => /^v\d+$/u.test(name)).sort();
  const lines = [
    "// Generated by scripts/runtime-types.ts from types/runtime (P085): do not edit.",
    "// Each runtime contract's type definitions, by version and capability (`porthole` is the call",
    "// contract every capability shares).",
    "export const RUNTIME_TYPES: Readonly<Record<string, Readonly<Record<string, string>>>> = {",
  ];
  for (const version of versions) {
    lines.push(`  ${JSON.stringify(version.slice(1))}: {`);
    const files = (await readdir(path.join(TYPES, version)))
      .filter((name) => name.endsWith(".d.ts"))
      .sort();
    for (const file of files) {
      const text = await readFile(path.join(TYPES, version, file), "utf8");
      lines.push(`    ${JSON.stringify(file.slice(0, -".d.ts".length))}: ${JSON.stringify(text)},`);
    }
    lines.push("  },");
  }
  lines.push("};", "");
  return lines.join("\n");
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const text = await generate();
  if (process.argv.includes("--check")) {
    const current = await readFile(GENERATED, "utf8").catch(() => "");
    if (current !== text) {
      process.stderr.write(
        "src/runtime/types.generated.ts is out of date: node scripts/runtime-types.ts\n",
      );
      process.exit(1);
    }
  } else {
    await writeFile(GENERATED, text);
  }
}
