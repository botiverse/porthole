/**
 * Writes the package's THIRD_PARTY_NOTICES.md (P097): every third-party package whose code the
 * package ships, which is its vendored libraries (P079) and what each one's file bundles, with each
 * package's license text, byte for byte, from the packages the lockfile installs.
 *
 *   node scripts/notices.ts          # write it
 *   node scripts/notices.ts --check  # exit 1 if it isn't what the packages hold
 *
 * `test/notices.test.ts` runs the check, so an upgrade can't leave the notices behind.
 */
import { readFile, readdir, realpath, stat, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import {
  VENDORED_LIBRARIES,
  libraryPath,
  type VendoredLibrary,
} from "../src/libraries/libraries.ts";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
export const NOTICES = path.join(root, "THIRD_PARTY_NOTICES.md");

/**
 * A library's dependencies its file doesn't bundle, each with the reason (checked against the
 * file: none of their code is in it). Everything else its dependencies reach is listed.
 */
const NOT_BUNDLED: Readonly<Record<string, Readonly<Record<string, string>>>> = {
  d3: {
    commander: "d3-dsv's command-line tools only",
    "iconv-lite": "d3-dsv's command-line tools only",
    rw: "d3-dsv's command-line tools only",
  },
};

interface Component {
  readonly name: string;
  readonly version: string;
  readonly license: string;
  readonly text: string;
}

interface Manifest {
  readonly name: string;
  readonly version: string;
  readonly license?: string;
  readonly dependencies?: Readonly<Record<string, string>>;
}

const exists = (file: string): Promise<boolean> =>
  stat(file).then(
    () => true,
    () => false,
  );

/** Where `name` resolves from `from`, as Node resolves it (pnpm keeps a package's deps beside it). */
async function resolve(from: string, name: string): Promise<string> {
  for (let dir = from; ; dir = path.dirname(dir)) {
    if (path.basename(dir) !== "node_modules") {
      const candidate = path.join(dir, "node_modules", name);
      if (await exists(path.join(candidate, "package.json"))) {
        return realpath(candidate);
      }
    }
    if (path.dirname(dir) === dir) {
      throw new Error(`${name} isn't installed where ${from} would find it`);
    }
  }
}

/** A package's license text: its LICENSE (or LICENCE), with or without an extension. */
async function licenseText(dir: string, file?: string): Promise<string> {
  const name = file ?? (await readdir(dir)).find((each) => /^licen[cs]e(?:\.\w+)?$/iu.test(each));
  if (name === undefined) {
    throw new Error(`no license file in ${dir}`);
  }
  return readFile(path.join(dir, name), "utf8");
}

/** The library's package first, then every package its file bundles, by name. */
async function components(library: VendoredLibrary): Promise<Component[]> {
  const skip = NOT_BUNDLED[library.name] ?? {};
  const found = new Map<string, Component>();
  const visit = async (dir: string, file?: string): Promise<void> => {
    const manifest = JSON.parse(await readFile(path.join(dir, "package.json"), "utf8")) as Manifest;
    const key = `${manifest.name}@${manifest.version}`;
    if (found.has(key)) {
      return;
    }
    found.set(key, {
      name: manifest.name,
      version: manifest.version,
      license: manifest.license ?? "UNKNOWN",
      text: await licenseText(dir, file),
    });
    for (const dependency of Object.keys(manifest.dependencies ?? {}).sort()) {
      if (!Object.hasOwn(skip, dependency)) {
        await visit(await resolve(dir, dependency));
      }
    }
  };
  const dir = await resolve(root, library.name);
  await visit(dir, library.licenseFile);
  const [own, ...rest] = [...found.values()];
  if (own?.version !== library.version) {
    throw new Error(`${library.name} is ${own?.version} in node_modules, not ${library.version}`);
  }
  return [own, ...rest.sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0))];
}

/** The file's text, from the installed packages. */
export async function generate(): Promise<string> {
  const lines = [
    "# Third-party notices",
    "",
    "`@botiverse/porthole` is licensed under Apache-2.0 ([LICENSE](LICENSE)). It also ships",
    "third-party code: the libraries `/server` serves to live widgets (P079), copied byte for byte",
    "from their npm packages into `src/libraries/files.generated.ts` (and `dist/`), each served with",
    "its own license beside it. Each library's file bundles the packages listed under it. Their",
    "license texts follow, as the packages pnpm installs for it carry them (the library's authors",
    "may have built its file from earlier releases of the same majors).",
    "",
    "Generated by `scripts/notices.ts` from the installed packages (P097): do not edit.",
    "",
  ];
  const texts = new Map<string, string[]>();
  for (const library of VENDORED_LIBRARIES) {
    const bundled = await components(library);
    lines.push(
      `## ${library.title} ${library.version}`,
      "",
      `Served at \`${libraryPath(library)}\` (npm's \`${library.file}\`), bundling:`,
      "",
      ...bundled.map((each) => `- ${each.name} ${each.version}: ${each.license}`),
      "",
    );
    for (const each of bundled) {
      const names = texts.get(each.text) ?? [];
      names.push(`${each.name} ${each.version}`);
      texts.set(each.text, names);
    }
  }
  lines.push("## License texts", "");
  for (const [text, names] of texts) {
    lines.push(`### ${names.join(", ")}`, "", "````text", text.trimEnd(), "````", "");
  }
  return lines.join("\n");
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const text = await generate();
  if (process.argv.includes("--check")) {
    const current = await readFile(NOTICES, "utf8").catch(() => "");
    if (current !== text) {
      process.stderr.write("THIRD_PARTY_NOTICES.md is out of date: node scripts/notices.ts\n");
      process.exit(1);
    }
  } else {
    await writeFile(NOTICES, text);
  }
}
