/**
 * Vendors Porthole's libraries (P079): copies each one's file and license, byte for byte, from its
 * npm package (pinned exactly in package.json, so the lockfile fixes the bytes) into
 * `src/libraries/files.generated.ts`, the module `/server` serves them from. A module rather than
 * files beside it, so every entry point still bundles whole (P075).
 *
 *   node scripts/vendor-libraries.ts          # write the module
 *   node scripts/vendor-libraries.ts --check  # exit 1 if it isn't what the packages hold
 *
 * `test/libraries.test.ts` runs the check, so the module can't drift from npm's files.
 */
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { VENDORED_LIBRARIES, libraryPath, licensePath } from "../src/libraries/libraries.ts";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
export const GENERATED = path.join(root, "src/libraries/files.generated.ts");

/** The module's text, from the installed packages. Throws if one isn't the pinned version. */
export async function generate(): Promise<string> {
  const entries: string[] = [];
  for (const library of VENDORED_LIBRARIES) {
    // The package as pnpm installed it for this one (a devDependency, pinned exactly).
    const dir = path.join(root, "node_modules", library.name);
    const manifest = path.join(dir, "package.json");
    const { version } = JSON.parse(await readFile(manifest, "utf8")) as { version: string };
    if (version !== library.version) {
      throw new Error(`${library.name} is ${version} in node_modules, not ${library.version}`);
    }
    const file = await readFile(path.join(dir, library.file), "utf8");
    const license = await readFile(path.join(dir, library.licenseFile), "utf8");
    entries.push(
      `  ${JSON.stringify(libraryPath(library))}: ${JSON.stringify(file)},`,
      `  ${JSON.stringify(licensePath(library))}: ${JSON.stringify(license)},`,
    );
  }
  return [
    "// Generated by scripts/vendor-libraries.ts from the pinned npm packages (P079): do not edit.",
    "// Each library's file and its license, byte for byte, by the path /server serves them at.",
    "export const LIBRARY_FILES: Readonly<Record<string, string>> = {",
    ...entries,
    "};",
    "",
  ].join("\n");
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const text = await generate();
  if (process.argv.includes("--check")) {
    const current = await readFile(GENERATED, "utf8").catch(() => "");
    if (current !== text) {
      process.stderr.write(
        "src/libraries/files.generated.ts is out of date: node scripts/vendor-libraries.ts\n",
      );
      process.exit(1);
    }
  } else {
    await writeFile(GENERATED, text);
  }
}
